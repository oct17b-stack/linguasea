import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { splitBundle } from './build';
import type { Bundle } from './bundle';

/** The generated TypeScript module with one lazy loader per course (see writeAppContent). */
export function coursesModule(keys: string[]): string {
  const lines = [...keys].sort().map((key) => `  '${key}': () => require('./${key}.json') as CourseBundle,`);
  return `// Generated by \`npm run content\` (packages/contract/src/cli/build.ts). Do not edit.
import type { CourseBundle } from '@linguasea/contract';

/**
 * One loader per (L1, course), keyed like courseKey(): "th-zh". Each require sits inside its function,
 * so the bundler includes the file but a course's JSON only becomes objects when it is opened.
 */
export const courseLoaders: Record<string, () => CourseBundle> = {
${lines.join('\n')}
};
`;
}

export type WrittenFile = { file: string; bytes: number };

/**
 * Writes the app's content into `dir` (app/src/content/generated): index.json, one
 * `<l1>-<target>.json` per course and courses.ts with their loaders. Files from an earlier build
 * are removed first, so a withdrawn course does not linger.
 */
export function writeAppContent(bundle: Bundle, dir: string): WrittenFile[] {
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(dir)) {
    if (f.endsWith('.json') || f === 'courses.ts') rmSync(join(dir, f));
  }
  const { index, courses } = splitBundle(bundle);
  const written: WrittenFile[] = [];
  const write = (file: string, text: string) => {
    writeFileSync(join(dir, file), text);
    written.push({ file, bytes: Buffer.byteLength(text) });
  };
  write('index.json', JSON.stringify(index) + '\n');
  for (const c of courses) write(`${c.key}.json`, JSON.stringify(c.course) + '\n');
  write('courses.ts', coursesModule(courses.map((c) => c.key)));
  return written;
}
